// Command ruledbgen writes aggregate_ruledb_gen.go: the category names of
// the geosite.dat shipped with Lanflow, which the aggregate editor's rule
// library searches (docs/aggregate.md). Run by go generate in
// internal/profile:
//
//	go run ./internal/ruledbgen ../../bin/geo/geosite.dat aggregate_ruledb_gen.go
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: ruledbgen geosite.dat out.go")
		os.Exit(2)
	}
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		fail(err)
	}
	names, err := categories(data)
	if err != nil {
		fail(err)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by ruledbgen from bin/geo/geosite.dat; DO NOT EDIT.\n\npackage profile\n\n")
	b.WriteString("// geositeCategories are the categories of the bundled geosite.dat, sorted.\n")
	b.WriteString("var geositeCategories = []string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q,\n", n)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(os.Args[2], src, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "ruledbgen:", err)
	os.Exit(1)
}

// categories reads the country_code of every entry of a GeoSiteList
// protobuf (field 1: repeated GeoSite; GeoSite field 1: string).
func categories(data []byte) ([]string, error) {
	var out []string
	for len(data) > 0 {
		key, n := uvarint(data)
		if n <= 0 {
			return nil, errors.New("bad tag")
		}
		data = data[n:]
		if key&7 != 2 {
			return nil, fmt.Errorf("unexpected wire type %d", key&7)
		}
		l, n := uvarint(data)
		if n <= 0 || uint64(len(data)-n) < l {
			return nil, errors.New("bad length")
		}
		entry := data[n : n+int(l)]
		data = data[n+int(l):]
		if key>>3 != 1 {
			continue
		}
		for len(entry) > 0 {
			k, m := uvarint(entry)
			if m <= 0 {
				return nil, errors.New("bad entry tag")
			}
			entry = entry[m:]
			switch k & 7 {
			case 0:
				_, m = uvarint(entry)
				entry = entry[m:]
			case 2:
				ln, m := uvarint(entry)
				if m <= 0 || uint64(len(entry)-m) < ln {
					return nil, errors.New("bad entry length")
				}
				if k>>3 == 1 {
					out = append(out, strings.ToLower(string(entry[m:m+int(ln)])))
				}
				entry = entry[m+int(ln):]
			default:
				return nil, fmt.Errorf("unexpected entry wire type %d", k&7)
			}
		}
	}
	sort.Strings(out)
	return out, nil
}

func uvarint(b []byte) (uint64, int) {
	var x uint64
	var s uint
	for i, c := range b {
		if i == 10 {
			return 0, -1
		}
		if c < 0x80 {
			return x | uint64(c)<<s, i + 1
		}
		x |= uint64(c&0x7f) << s
		s += 7
	}
	return 0, 0
}
